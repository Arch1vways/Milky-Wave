#!/usr/bin/env python3
"""OriginWave.svg -> launcher icon layers (adaptive icon foreground and themed monochrome).

Usage: python3 tools/make_icon.py [path/to/OriginWave.svg]

The SVG may contain only <rect> elements (with rx/ry for rounded corners). Its square artboard is mapped onto the
72dp safe area of the 108dp adaptive icon, the colours of the SVG go into the foreground, white into the monochrome
layer. Without an argument the SVG next to the project folder is used.
"""
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
DEFAULT_SVG = os.path.join(os.path.dirname(PROJECT), 'OriginWave.svg')
OUT = os.path.join(PROJECT, 'app', 'src', 'main', 'res', 'drawable')
SVG_NS = '{http://www.w3.org/2000/svg}'
ICON_DP, SAFE_DP = 108.0, 72.0


def num(v, digits=4):
    s = ('%.*f' % (digits, v)).rstrip('0').rstrip('.')
    return '0' if s in ('', '-0') else s


def rounded_rect(x, y, w, h, rx, ry):
    rx, ry = min(rx, w / 2), min(ry, h / 2)
    if rx <= 0 or ry <= 0:
        return 'M%s,%sH%sV%sH%sZ' % (num(x), num(y), num(x + w), num(y + h), num(x))
    a = 'A%s,%s 0 0 1 ' % (num(rx), num(ry))
    return ('M{l1},{t}H{r1}{a}{r},{t1}V{b1}{a}{r1},{b}H{l1}{a}{l},{b1}V{t1}{a}{l1},{t}Z').format(
        l=num(x), t=num(y), r=num(x + w), b=num(y + h), l1=num(x + rx), r1=num(x + w - rx),
        t1=num(y + ry), b1=num(y + h - ry), a=a)


def android_color(c):
    c = c.strip().lstrip('#')
    if len(c) == 3:
        c = ''.join(ch * 2 for ch in c)
    if len(c) != 6:
        raise SystemExit('unsupported colour: #' + c)
    return '#FF' + c.upper()


def main():
    svg = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SVG
    root = ET.parse(svg).getroot()
    vb = [float(v) for v in root.get('viewBox', '0 0 %s %s' % (root.get('width'), root.get('height'))).split()]
    vx, vy, vw, vh = vb
    if abs(vw - vh) > 1e-6:
        raise SystemExit('the artboard has to be square, got %sx%s' % (vw, vh))
    shapes = []
    for el in root.iter():
        tag = el.tag.replace(SVG_NS, '')
        if tag == 'svg':
            continue
        if tag != 'rect':
            raise SystemExit('only <rect> is supported, found <%s>' % tag)
        x, y = float(el.get('x', 0)), float(el.get('y', 0))
        w, h = float(el.get('width')), float(el.get('height'))
        rx = el.get('rx')
        ry = el.get('ry')
        rx = float(rx if rx is not None else (ry if ry is not None else 0))
        ry = float(ry if ry is not None else rx)
        fill = el.get('fill')
        if not fill or fill == 'none':
            raise SystemExit('a rect without a fill colour')
        shapes.append((android_color(fill), rounded_rect(x - vx, y - vy, w, h, rx, ry)))
    if not shapes:
        raise SystemExit('no shapes in ' + svg)
    scale = SAFE_DP / vw
    offset = (ICON_DP - SAFE_DP) / 2

    def layer(color_of):
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            '<!-- Generated by tools/make_icon.py from OriginWave.svg: %sx%s artboard mapped onto the 72dp'
            ' adaptive-icon viewport. -->' % (num(vw), num(vh)),
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    android:width="108dp"',
            '    android:height="108dp"',
            '    android:viewportWidth="108"',
            '    android:viewportHeight="108">',
            '    <group',
            '        android:translateX="%s"' % num(offset),
            '        android:translateY="%s"' % num(offset),
            '        android:scaleX="%s"' % num(scale, 6),
            '        android:scaleY="%s">' % num(scale, 6),
            '        <clip-path android:pathData="M0,0H%sV%sH0Z" />' % (num(vw), num(vh)),
        ]
        for color, path in shapes:
            lines.append('        <path android:fillColor="%s"' % color_of(color))
            lines.append('            android:pathData="%s" />' % path)
        lines += ['    </group>', '</vector>', '']
        return '\n'.join(lines)

    os.makedirs(OUT, exist_ok=True)
    for name, color_of in (('ic_launcher_foreground.xml', lambda c: c),
                           ('ic_launcher_monochrome.xml', lambda c: '#FFFFFFFF')):
        with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(layer(color_of))
        print('written', os.path.join(OUT, name))
    print('%d shapes from %s' % (len(shapes), svg))


if __name__ == '__main__':
    main()
